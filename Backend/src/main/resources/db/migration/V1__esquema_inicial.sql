-- Esquema inicial de JukeBox: las mismas tablas que creaba Hibernate con ddl-auto=update.
-- En una base que ya existía, Flyway no corre este archivo (ver baseline en lecciones/flyway-migraciones.md).

CREATE TABLE rooms (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(10)  NOT NULL UNIQUE,
    name          varchar(100),
    owner_user_id bigint,
    is_active     boolean,
    created_at    timestamp(6)
);

CREATE TABLE users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       varchar(50)  NOT NULL UNIQUE,
    email          varchar(254) UNIQUE,
    email_verified boolean,
    password       varchar(255) NOT NULL,
    session_token  varchar(255) UNIQUE,
    ip_address     varchar(45),
    room_id        bigint
);

CREATE TABLE songs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    youtube_id       varchar(20)  NOT NULL UNIQUE,
    title            varchar(255) NOT NULL,
    artist           varchar(100),
    thumbnail_url    varchar(255),
    duration_seconds integer
);

CREATE TABLE queue (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id          bigint,
    song_id          bigint,
    added_by_user_id bigint,
    status           varchar(20) CHECK (status IN ('PENDING', 'PLAYING', 'PLAYED', 'SKIPPED')),
    votes_count      integer,
    added_at         timestamp(6),
    played_at        timestamp(6)
);

CREATE TABLE votes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    queue_id   bigint,
    user_id    bigint,
    vote_type  integer,
    created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (queue_id, user_id)
);

CREATE TABLE cooldowns (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id    bigint,
    identifier varchar(100),
    type       varchar(255) CHECK (type IN ('SONG', 'ARTIST')),
    expires_at timestamp(6)
);

CREATE TABLE email_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint      NOT NULL,
    token_hash varchar(64) NOT NULL UNIQUE,
    type       varchar(30) NOT NULL CHECK (type IN ('VERIFY_EMAIL', 'RESET_PASSWORD')),
    expires_at timestamp(6) with time zone NOT NULL,
    used_at    timestamp(6) with time zone
);

